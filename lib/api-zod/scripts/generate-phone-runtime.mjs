import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

// Metro follows every re-export in the upstream barrel. Prebundle ONLY this
// facade, rather than enabling unstable, app-wide Metro graph optimizations.
// Use public entrypoints and the unchanged default (min) worldwide metadata.
const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const version = require("libphonenumber-js/package.json").version;
const license = readFileSync(new URL("../node_modules/libphonenumber-js/LICENSE", import.meta.url), "utf8");
const result = await build({
  absWorkingDir: root,
  stdin: {
    contents: 'export { getCountries, getCountryCallingCode, parsePhoneNumberFromString } from "libphonenumber-js";',
    resolveDir: root,
    sourcefile: "phone-runtime-entry.js",
  },
  bundle: true,
  format: "esm",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "es2020",
  minify: true,
  metafile: true,
  write: false,
  banner: { js: `// Generated by pnpm --filter @workspace/api-zod generate:phone; DO NOT EDIT.\n// libphonenumber-js ${version}; unchanged worldwide metadata.min.\n/*\n${license}\n*/` },
});
const retained = Object.entries(result.metafile.outputs).flatMap(([, output]) =>
  Object.entries(output.inputs).filter(([, input]) => input.bytesInOutput > 0).map(([name]) => name));
if (retained.some(name => /AsYouType|PhoneNumberMatcher|findNumbers|searchNumbers/.test(name))) {
  throw new Error("Unused formatting/search code was retained in the phone facade");
}
if (!retained.some(name => name.endsWith("metadata.min.json.js"))) {
  throw new Error("The original worldwide metadata.min must be retained");
}
const output = new URL("../src/phone-runtime.js", import.meta.url);
const content = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== content) {
    throw new Error("Phone runtime is stale. Run pnpm --filter @workspace/api-zod generate:phone and test:phone before committing.");
  }
} else {
  writeFileSync(output, content);
}
console.log(`Phone facade: ${Buffer.byteLength(content)} bytes; ${retained.length} retained modules; no AsYouType/search/matcher code.`);