/**
 * Filter-reminder sync endpoint for the Ultra-Clear Companion app.
 *
 * The app keeps the authoritative filter activation in AsyncStorage and
 * schedules local push notifications itself. This route receives a mirror of
 * that activation so the daily server job (lib/reminder-dispatch.ts) can also
 * deliver lifecycle reminders via email / SMS / WhatsApp for opted-in users.
 *
 * PUT /api/uc/reminders/sync   (authenticated)
 *   Body: { activation: null | {
 *     productId: number, productName: string, lifespanDays: number,
 *     activatedAt: string (ISO), sourceOrderId?: number
 *   } }
 *   - null  → the user cleared their activation: soft-disable the row.
 *   - value → upsert. Starting a new cycle (different product or activation
 *             date) resets the sent-stage tracking.
 */
import { Router, type IRouter, type Request, type Response } from "express";
import { eq, and, isNull, sql } from "drizzle-orm";
import { db, ucFilterRemindersTable, ucUsersTable } from "@workspace/db";
import { verifyToken } from "../lib/jwt.js";
import { logger } from "../lib/logger";
import { lookupLimiter } from "../lib/rate-limiters.js";

const router: IRouter = Router();

/** Oldest activation date the server accepts (guards sent-stage reset abuse). */
const MAX_ACTIVATION_AGE_MS = 3 * 365 * 86_400_000; // 3 years
/** Small clock-skew allowance for "future" activation timestamps. */
const MAX_FUTURE_SKEW_MS = 60 * 60 * 1000; // 1 hour

interface SyncBody {
  activation: null | {
    productId: number;
    productName: string;
    lifespanDays: number;
    /**
     * Performance-adjusted effective lifespan from the app (water quality /
     * clean history). When present and valid, stored separately so the
     * dispatcher can still compute day30/day60 stages with the right lifespan.
     * Omitted when no adjustment has been made.
     */
    effectiveLifespanDays?: number;
    /**
     * Day-offsets (from activatedAt) for the two replacement stages, computed
     * by the app at check-in time. The server dispatcher uses these directly
     * instead of the formula so both channels fire on the exact same dates —
     * critical for late check-ins where the "tomorrow" guard shifts the offset
     * past what the lifespan formula would produce.
     */
    adjustedReplaceOffsets?: { replace30: number; replace15: number };
    activatedAt: string;
    sourceOrderId?: number;
    /**
     * ISO timestamp generated by the client at the moment this sync request
     * is fired. The server uses this as a monotonic version: it rejects a
     * write for the same cycle when the stored syncedAt is already newer,
     * preventing a slow earlier request from overwriting a faster later one.
     */
    syncedAt?: string;
  };
}

router.put("/uc/reminders/sync", lookupLimiter, async (req: Request, res: Response): Promise<void> => {
  const claims = verifyToken(req.headers["authorization"]);
  const userId = claims ? String(claims.id ?? "") : "";
  if (!userId || !/^\d+$/.test(userId)) {
    res.status(401).json({ error: "Authentication required" });
    return;
  }

  // Deleted accounts must not keep receiving messages.
  const [user] = await db
    .select({ id: ucUsersTable.id })
    .from(ucUsersTable)
    .where(and(eq(ucUsersTable.id, Number(userId)), isNull(ucUsersTable.deletedAt)))
    .limit(1);
  if (!user) {
    res.status(401).json({ error: "Authentication required" });
    return;
  }

  const body = req.body as SyncBody;
  if (!body || !("activation" in body)) {
    res.status(400).json({ error: "Missing activation field" });
    return;
  }

  try {
    if (body.activation === null) {
      // Soft-disable — keeps sent-stage history in case the same cycle returns.
      await db
        .update(ucFilterRemindersTable)
        .set({ active: false, updatedAt: new Date() })
        .where(eq(ucFilterRemindersTable.userId, userId));
      res.json({ ok: true, active: false });
      return;
    }

    const a = body.activation;
    const activatedAt = new Date(a.activatedAt);
    if (
      !Number.isInteger(a.productId) ||
      typeof a.productName !== "string" ||
      a.productName.length === 0 ||
      a.productName.length > 300 ||
      typeof a.lifespanDays !== "number" ||
      !Number.isFinite(a.lifespanDays) ||
      a.lifespanDays < 0 ||
      a.lifespanDays > 10000 ||
      Number.isNaN(activatedAt.getTime()) ||
      (a.sourceOrderId != null && !Number.isInteger(a.sourceOrderId)) ||
      (a.effectiveLifespanDays != null && (
        typeof a.effectiveLifespanDays !== "number" ||
        !Number.isFinite(a.effectiveLifespanDays) ||
        a.effectiveLifespanDays < 0 ||
        a.effectiveLifespanDays > 10000
      )) ||
      (a.adjustedReplaceOffsets != null && (
        typeof a.adjustedReplaceOffsets !== "object" ||
        !Number.isInteger(a.adjustedReplaceOffsets.replace30) ||
        !Number.isInteger(a.adjustedReplaceOffsets.replace15) ||
        a.adjustedReplaceOffsets.replace30 < 0 ||
        a.adjustedReplaceOffsets.replace15 < 0 ||
        a.adjustedReplaceOffsets.replace30 > 10000 ||
        a.adjustedReplaceOffsets.replace15 > 10000
      ))
    ) {
      res.status(400).json({ error: "Invalid activation payload" });
      return;
    }

    // Activation date sanity — blocks sent-stage reset abuse via wandering
    // timestamps (each "new cycle" re-arms reminder messages).
    const age = Date.now() - activatedAt.getTime();
    if (age < -MAX_FUTURE_SKEW_MS || age > MAX_ACTIVATION_AGE_MS) {
      res.status(400).json({ error: "Activation date out of range" });
      return;
    }

    const [existing] = await db
      .select()
      .from(ucFilterRemindersTable)
      .where(eq(ucFilterRemindersTable.userId, userId))
      .limit(1);

    // ── Validate and parse syncedAt ───────────────────────────────────────────
    // syncedAt is generated by the client at call-time and used as a monotonic
    // version for stale-write rejection at the DB level.  Accept only a valid
    // finite ISO date; fall back to now() when absent so older clients and
    // first-install syncs (no stored syncedAt) always succeed.
    let incomingSyncedAt: Date;
    if (a.syncedAt != null) {
      const parsed = new Date(a.syncedAt);
      if (isNaN(parsed.getTime())) {
        res.status(400).json({ error: "Invalid syncedAt value" });
        return;
      }
      incomingSyncedAt = parsed;
    } else {
      incomingSyncedAt = new Date();
    }

    // isExistingCycle: an existing row for this exact filter cycle is present.
    // A missing row (first sync after login/offline gap) is NOT a cycle change —
    // the app sends the correct offsets from its local state and the server must
    // honour them.  A cycle change only happens when an existing row describes a
    // different product or a different activation timestamp.
    const isExistingCycle =
      !!existing &&
      existing.productId === a.productId &&
      existing.activatedAt.getTime() === activatedAt.getTime();

    // isNewCycle: an existing row exists but describes a different filter cycle.
    // Triggers a sent-stages reset; adjustment fields are also cleared because
    // they belonged to the previous cycle.
    const isNewCycle =
      !!existing && !isExistingCycle;

    // effectiveLifespanDays: accept a valid positive integer from the app.
    // Preserved on first insert (no existing row) and on continuation of the
    // same cycle. Reset to null only when replacing an existing different cycle.
    const effectiveLifespanDays =
      a.effectiveLifespanDays != null && a.effectiveLifespanDays > 0 && !isNewCycle
        ? Math.min(Math.floor(a.effectiveLifespanDays), Math.floor(a.lifespanDays))
        : null;

    // adjustedReplaceOffsets: day-offsets the app computed at check-in time.
    // Lower-clamp to 1; no upper-clamp at lifespanDays because a late check-in
    // legitimately computes replace30 = elapsed + 1 which can exceed rated life.
    // Preserved on first insert and same-cycle continuation; reset only on cycle
    // change (different product or activation timestamp).
    const ratedDays = Math.floor(a.lifespanDays);
    const adjustedReplaceOffsets =
      a.adjustedReplaceOffsets != null && !isNewCycle
        ? {
            replace30: Math.max(1, Math.floor(a.adjustedReplaceOffsets.replace30)),
            replace15: Math.max(1, Math.floor(a.adjustedReplaceOffsets.replace15)),
          }
        : null;

    const values = {
      productId: a.productId,
      productName: a.productName.trim(),
      lifespanDays: ratedDays,
      effectiveLifespanDays,
      adjustedReplaceOffsets,
      activatedAt,
      sourceOrderId: a.sourceOrderId ?? null,
      active: true,
      syncedAt: incomingSyncedAt,
      updatedAt: new Date(),
      ...(isNewCycle ? { sentStages: [] as string[] } : {}),
    };

    // ── Atomic stale-write rejection ──────────────────────────────────────────
    // The client fires syncReminderToServer fire-and-forget; network delivery
    // order is not guaranteed. Two overlapping requests can both read the
    // current row before either writes; the newer one commits first, then the
    // older one arrives and would overwrite the adjusted offsets — leaving
    // email/SMS/WhatsApp on the stale schedule.
    //
    // Guard: move the staleness check into the ON CONFLICT … WHERE clause so it
    // is evaluated atomically inside the Postgres transaction.  The update only
    // proceeds when the incoming syncedAt is ≥ what is already stored (or when
    // the stored value is NULL, i.e. an older client or a first-sync).
    // If the WHERE clause rejects the update, RETURNING returns 0 rows → stale.
    //
    // Cycle changes (different product / activation date) always win — they
    // carry a fresh syncedAt and reset the stored value.
    const upserted = await db
      .insert(ucFilterRemindersTable)
      .values({ userId, ...values, sentStages: isNewCycle ? [] : (existing?.sentStages ?? []) })
      .onConflictDoUpdate({
        target: ucFilterRemindersTable.userId,
        set: values,
        where: sql`uc_filter_reminders.synced_at IS NULL OR EXCLUDED.synced_at >= uc_filter_reminders.synced_at`,
      })
      .returning({ userId: ucFilterRemindersTable.userId });

    // A same-cycle update that produced 0 rows means the WHERE clause blocked it
    // — the stored syncedAt is already newer. Silently ack (200) so the app does
    // not retry; the server state is already correct.
    if (upserted.length === 0) {
      res.json({ ok: true, active: true, newCycle: false, stale: true });
      return;
    }

    res.json({ ok: true, active: true, newCycle: isNewCycle });
  } catch (err) {
    logger.error({ err, userId }, "reminder sync failed");
    res.status(500).json({ error: "Failed to sync reminder" });
  }
});

export default router;
